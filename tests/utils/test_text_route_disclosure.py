def test_text_returns_only_the_callers_own_bytes_and_reads_no_storage(
    client, monkeypatch
):
    """The honest statement of this route's tenant boundary, written after
    MEASURING it rather than assuming it.

    `/text` does not query the vector store at all -- it extracts from the bytes on
    THIS request and returns them. So a token from another tenant that legitimately
    carries `ent=['userA']` gets back only what it just uploaded itself; there is no
    stored tenant content on this route for it to cross into. The boundary that
    actually governs here is the entitlement (asserted above), and the property worth
    pinning is that the route never reads storage -- because that is what would have
    to change for a cross-tenant read to become possible.

    Recorded for Core, who owns the central grant/group/exclusion policy: `tid` is
    verified as PRESENT by the middleware but is not used as a scoping filter on this
    route. That is sound only while the route reads nothing; this test fails if that
    ever stops being true.
    """
    reads = []

    async def recording_get(self, ids, *a, **kw):
        reads.append(ids)
        return []

    monkeypatch.setattr(AsyncPgVector, "get_documents_by_ids", recording_get, raising=False)

    r = _text(client, entity_id="userA", ent=["userA"], tid="tenantB", content=b"mine")

    assert r.status_code == 200, r.text
    assert r.json()["text"] == "mine", "the route returned something other than the caller's own bytes"
    assert reads == [], f"/text read from the vector store: {reads}"
    assert client.inserted_batches == []


