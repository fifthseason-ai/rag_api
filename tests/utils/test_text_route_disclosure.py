def test_content_rejection_stays_permanent_and_names_the_format(client):
    """A real unsupported binary keeps its terminal verdict. The fix must not sweep
    honest content verdicts into 'our side, try again' -- that would retry forever a
    file that can never work."""
    png = b"\x89PNG\r\n\x1a\n" + b"\x00" * 64
    r = _text(client, filename="diagram.png", content=png, content_type="image/png")

    assert r.status_code == 422, f"got {r.status_code}: {r.text}"
    assert r.status_code != 503
    detail = r.json()["detail"]
    assert detail["extraction"]["status"] == "unsupported"
    # The verdict names the format rather than guessing at the bytes.
    assert detail["extraction"]["verdict"]


def test_temp_file_is_cleaned_up_even_when_extraction_fails(client, monkeypatch):
    """The `finally` cleanup is part of 'no partial state'. Prove it still runs."""
    seen = {}
    real_cleanup = document_routes.cleanup_temp_file_async

    async def recording_cleanup(path):
        seen["path"] = path
        return await real_cleanup(path)

    def boom(documents, file_ext):
        raise ValueError(f"nope {_MARKER}")

    monkeypatch.setattr(document_routes, "cleanup_temp_file_async", recording_cleanup)
    monkeypatch.setattr(document_routes, "extract_text_from_documents", boom)

    _text(client)

    assert "path" in seen, "the temp file was never cleaned up after a failure"
    assert not os.path.exists(seen["path"])


