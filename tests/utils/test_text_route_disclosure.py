"""Route-level proof for the LAST caller-facing `str(e)` on the file-intake surface:
the `/text` outer exception handler (FILES-01 F2).

Why this file exists at all, and why it is a ROUTE test rather than a unit test
==============================================================================
KI-02 SP-01.10 routed the `load_file_content` seam through `describe_failure`, and
SP-01.13 did the same for the upload-save path. SP-01.13 ALSO changed the `/text`
outer handler and then **deliberately reverted it**, because the branch is reachable
only through the full route -- entitlement, path validation and request state all
have to be satisfied before the `try` block runs -- and a change no test could turn
red is not shippable. That judgement was right; this file supplies the missing
harness rather than arguing with it.

What is still unprotected there, established by reading the route and proven below
==================================================================================
Inside `/text`'s `try` block, `save_upload_file_async` and `load_file_content` now
raise `HTTPException` and are re-raised untouched by the `except HTTPException`
branch. Two calls are NOT behind either seam:

  * `os.makedirs(os.path.dirname(validated_temp_file_path), ...)` -- a permission or
    disk failure here raises a bare `OSError` whose `str()` contains OUR temp path.
  * `extract_text_from_documents(data, file_ext)` -- any failure raises raw.

Both land in `except Exception` and are echoed to the caller as
`f"Error during text extraction: {str(e)}"`. That is the leak, and it is also a
mis-attribution: every one of those failures is answered `400`, telling the caller
their file is bad and telling Core's listener not to retry, for faults that are ours.

The marker convention
=====================
Injected exceptions carry `_MARKER`, a string that could only have come from the
exception's own text. Asserting `_MARKER not in response` is a stronger claim than
asserting some particular sentence IS present: it cannot pass by accident and it
cannot be satisfied by a reworded message.

Everything here is SYNTHETIC -- generated bytes and injected exceptions. No client
content, no network, no database. The vector store is simulated and every insert
attempt is recorded, so "nothing was written" is asserted against actual calls
rather than assumed from a status code.
"""

import datetime
import io
import os
import re
from concurrent.futures import ThreadPoolExecutor

import jwt
