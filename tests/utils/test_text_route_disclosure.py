_SECRET = "test_key"

# A token that can only have travelled out of an exception's own message, plus an
# internal-looking path of the exact shape `_make_unique_temp_path` produces.
_MARKER = "FILES01-INTERNAL-MARKER-9fce21ab"
_FAKE_INTERNAL_PATH = "/tmp/uploads/tenantA/q4-forecast_0123456789abcdef.xlsx"

# `describe_failure` hands the caller a 12-hex reference tying the answer to the log.
_REFERENCE = re.compile(r"Reference: [0-9a-f]{12}\.")


def _hdr(ent, act, tid="tenantA", uid="testuser"):
    os.environ["JWT_SECRET"] = _SECRET
    payload = {
        "id": uid,
        "tid": tid,
        "ent": ent,
        "act": act,
        "exp": datetime.datetime.now(datetime.timezone.utc)
        + datetime.timedelta(hours=1),
    }
    return {"Authorization": f"Bearer {jwt.encode(payload, _SECRET, algorithm='HS256')}"}


@pytest.fixture()
def client(monkeypatch):
    """TestClient with the vector store SIMULATED and every insert attempt recorded.

    `/text` must never write, on success OR on failure; recording the calls lets the
    tests assert that against reality instead of inferring it from a status code.
    """
    os.environ["JWT_SECRET"] = _SECRET
    if not hasattr(app.state, "thread_pool") or app.state.thread_pool is None:
        app.state.thread_pool = ThreadPoolExecutor(max_workers=2)

    added = []

    async def recording_aadd(self, docs, ids=None, executor=None):
        added.append(list(docs))
        return ids

    monkeypatch.setattr(AsyncPgVector, "aadd_documents", recording_aadd)

    test_client = TestClient(app)
    test_client.inserted_batches = added  # type: ignore[attr-defined]
    return test_client


def _text(
    client,
    filename="notes.txt",
    content=b"hello world",
    *,
    content_type="text/plain",
    entity_id="userA",
    ent=None,
    act=None,
    tid="tenantA",
):
    """Drive the real route with LEGITIMATE authorization inputs.

    The defaults are a request that is allowed: `act=['read']` (what Core mints for
    `/text`) and an entitlement containing the entity being addressed. The error
    branch under test only executes once all of that has passed, which is precisely
    why a unit test could not reach it.
    """
    return client.post(
        "/text",
        data={"file_id": "f-text-1", "entity_id": entity_id},
        files={"file": (filename, io.BytesIO(content), content_type)},
        headers=_hdr(
            ent=ent if ent is not None else [entity_id],
            act=act if act is not None else ["read"],
            tid=tid,
        ),
    )


