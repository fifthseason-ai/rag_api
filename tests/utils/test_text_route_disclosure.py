def test_extraction_failure_never_echoes_the_exception_to_the_caller(
    client, monkeypatch
):
    """A failure in `extract_text_from_documents` must not hand the caller our
    exception text -- which here carries an internal path."""

    def boom(documents, file_ext):
        raise ValueError(f"cannot decode column at {_FAKE_INTERNAL_PATH} {_MARKER}")

    monkeypatch.setattr(document_routes, "extract_text_from_documents", boom)

    r = _text(client)

    body = r.text
    assert _MARKER not in body, f"exception text reached the caller: {body}"
    assert _FAKE_INTERNAL_PATH not in body, f"internal path reached the caller: {body}"
    assert "/tmp/uploads" not in body
    # The caller is not left with nothing: a reference ties the answer to the log.
    assert _REFERENCE.search(body), f"no reference for the operator to look up: {body}"


def test_makedirs_permission_failure_does_not_leak_our_temp_path(client, monkeypatch):
    """The first unprotected call in the route. A real `PermissionError` puts our
    own upload directory in `str(e)`; that must not be the caller's answer."""
    real_makedirs = os.makedirs

    def boom(path, *args, **kwargs):
        raise PermissionError(
            13, f"Permission denied: '{os.path.dirname(_FAKE_INTERNAL_PATH)}' {_MARKER}"
        )

    monkeypatch.setattr(document_routes.os, "makedirs", boom)
    try:
        r = _text(client)
    finally:
        monkeypatch.setattr(document_routes.os, "makedirs", real_makedirs)

    body = r.text
    assert _MARKER not in body, f"exception text reached the caller: {body}"
    assert "/tmp/uploads" not in body, f"internal path reached the caller: {body}"
    # Review note: absence-only assertions would also pass for a wrong status or a
    # message with nothing the operator can look up. Pin both.
    assert r.status_code == 503, f"our own directory failing is ours: {r.status_code}"
    assert _REFERENCE.search(body), f"no reference for the operator: {body}"


def test_our_outage_is_retryable_and_does_not_blame_the_file(client, monkeypatch):
    """A `MemoryError` building the text is OUR fault. Answering `400` tells Core's
    listener the file is bad and not to retry -- the exact mis-attribution SP-01.10
    exists to prevent, still live on this route."""

    def boom(documents, file_ext):
        raise MemoryError(f"cannot allocate 4.2 GiB {_MARKER}")

    monkeypatch.setattr(document_routes, "extract_text_from_documents", boom)

    r = _text(client)

    assert r.status_code == 503, (
        f"a service fault was reported as a client fault ({r.status_code}); "
        f"body={r.text}"
    )
    assert _MARKER not in r.text
    assert "not with your file" in r.text


