def test_locked_pdf_is_named_as_encrypted_at_the_loader(tmp_path):
    """The verdict is decided at the loader, before parsing -- the same place
    SheetExcelLoader decides encrypted-vs-corrupt from the container."""
    path = tmp_path / "locked.pdf"
    path.write_bytes(_pdf(user_password="userpw"))

    loader = SafePyPDFLoader(str(path))
    with pytest.raises(EncryptedDocumentError) as exc:
        list(loader.lazy_load())

    assert exc.value.verdict == "encrypted"
    message = str(exc.value).lower()
    assert "password-protected" in message
    assert "without a password" in message, "the message must say what to DO"


def test_locked_pdf_gets_the_same_422_contract_as_a_locked_workbook(client, tmp_path):
    """Route level: 422, verdict `encrypted`, zero rows -- identical in shape to the
    encrypted-xlsx answer, which is the whole point of the change."""
    r = _embed(client, "locked.pdf", _pdf(user_password="userpw"))

    assert r.status_code == 422, r.text
    detail = r.json()["detail"]
    assert detail["extraction"]["verdict"] == "encrypted"
    assert "without a password" in detail["message"]
    assert client.written == [], "a refused file must write nothing"


def test_the_old_unhelpful_answer_is_gone(client, tmp_path):
    """RED before the change: a locked PDF used to answer 400 'the cause is not
    established', which tells the uploader nothing they can act on."""
    r = _embed(client, "locked.pdf", _pdf(user_password="userpw"))

    assert r.status_code != 400
    assert "cause is not established" not in r.text


