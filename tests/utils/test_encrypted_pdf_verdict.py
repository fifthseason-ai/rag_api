_SECRET = "test_key"
PDF = "application/pdf"


def _pdf(user_password=None, owner_password=None, pages=1, text_hint=None):
    """A real PDF built by pypdf. `text_hint` is unused for blank pages but keeps the
    intent readable at the call site."""
    from pypdf import PdfWriter

    w = PdfWriter()
    for _ in range(pages):
        w.add_blank_page(width=200, height=200)
    if user_password is not None or owner_password is not None:
        w.encrypt(
            user_password=user_password if user_password is not None else "",
            owner_password=owner_password,
        )
    buf = io.BytesIO()
    w.write(buf)
    return buf.getvalue()


def _hdr(act="write", entity="userA"):
    os.environ["JWT_SECRET"] = _SECRET
    payload = {
        "id": "testuser",
        "tid": "tenantA",
        "ent": [entity],
        "act": [act],
        "exp": datetime.datetime.now(datetime.timezone.utc) + datetime.timedelta(hours=1),
    }
    return {"Authorization": f"Bearer {jwt.encode(payload, _SECRET, algorithm='HS256')}"}


@pytest.fixture()
def client(monkeypatch):
    os.environ["JWT_SECRET"] = _SECRET
    if not hasattr(app.state, "thread_pool") or app.state.thread_pool is None:
        app.state.thread_pool = ThreadPoolExecutor(max_workers=2)
    written = []

    async def rec(self, docs, ids=None, executor=None):
        written.append(list(docs))
        return ids or ["id1"]

    monkeypatch.setattr(AsyncPgVector, "aadd_documents", rec)
    c = TestClient(app)
    c.written = written  # type: ignore[attr-defined]
    return c


def _embed(client, name, data):
    return client.post(
        "/embed",
        data={"file_id": "pdf-1", "entity_id": "userA"},
        files={"file": (name, io.BytesIO(data), PDF)},
        headers=_hdr(),
    )


