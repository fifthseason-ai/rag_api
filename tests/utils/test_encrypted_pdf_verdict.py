"""A password-protected PDF gets the same actionable verdict a workbook already gets
(FILES-01, approved as a small maintenance change 2026-09-17).

Before this, an encrypted .xlsx answered `422` with verdict `encrypted` and a sentence
the uploader can act on -- "save it without a password" -- while an encrypted PDF in the
identical situation answered the generic `400 "the cause is not established"`. Same
condition, two different answers, and only one of them tells the user what to do.

THE TRAP THIS FILE EXISTS TO GUARD, because it is what makes the obvious fix wrong
=================================================================================
"Encrypted" means two different things for a PDF, and only one is a refusal. Measured
with pypdf in the shipped image before anything was written:

    user password        is_encrypted=True, decrypt("") -> 0  pages UNREADABLE
    owner password ONLY  is_encrypted=True, decrypt("") -> 1  pages READ FINE

Owner-password PDFs carry usage restrictions (no printing, no copying) and extract
perfectly well today. A fix keyed on `is_encrypted` would have refused a whole class of
files that currently work -- a regression dressed as an improvement. The condition is
therefore "the empty password does not unlock it", and
`test_owner_password_only_pdf_still_extracts` is the test that keeps it that way.

Deliberately NOT built, and not wanted: password storage, password prompting, or any
attempt to break a password. This only names what is wrong.

Fixtures are generated by pypdf at test time. No client content.
"""

